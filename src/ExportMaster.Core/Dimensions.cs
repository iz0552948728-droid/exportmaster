namespace ExportMaster.Core;

/// <summary>
/// Типы значений структурных элементов многомерной матрицы (ТЗ п. 4.2.1.2, поле 3.1).
/// </summary>
/// <remarks>
/// Значения заданы явно и совпадают с байтом в файле данных. Нумерация с нуля,
/// принятая в C# по умолчанию, привела бы к чтению не той оси: разбор не упал бы,
/// а выдал правдоподобные, но неверные значения.
/// Эти же имена используются в списке отбора данных шаблона и в ключе
/// результирующего файла (ТЗ п. 4.4.5).
/// </remarks>
public enum Dimensions : byte
{
    /// <summary>Частота.</summary>
    FREQ = 1,

    /// <summary>Поляризация зонда.</summary>
    POL1 = 2,

    /// <summary>Канал.</summary>
    CHANNEL = 3,

    /// <summary>Луч.</summary>
    BEAM = 4,

    /// <summary>Позиция по оси сбора данных.</summary>
    DATA = 5,

    /// <summary>Позиция движения.</summary>
    POS = 6,

    /// <summary>Позиция слайдера.</summary>
    SLIDER = 7,

    /// <summary>Поляризация приёмника.</summary>
    POL2 = 8,
}
